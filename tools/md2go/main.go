// Command md2go converts the project's Markdown documentation into Go files
// that live beside the frontend routes.
//
// Usage:
//
//	go generate ./src/routes
//
// Each docs/<name>.md becomes src/routes/docs_<name>.go containing the source as
// a Go constant. A docs_manifest.go file lists every converted document so the
// docs routes can render them without runtime file access.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

var (
	markdownLink = regexp.MustCompile(`\[([^\]]+)\]\([^)]+\)`)
	markdownCode = regexp.MustCompile("`+")
	markdownBold = regexp.MustCompile(`\*\*|__`)
	markdownEm   = regexp.MustCompile(`\*+`)
)

type document struct {
	Slug     string
	Title    string
	Summary  string
	Filename string
	Const    string
}

func main() {
	docsDir := flag.String("docs", "docs", "directory containing Markdown files")
	outDir := flag.String("out", "src/routes", "directory for generated Go files")
	pkg := flag.String("package", "routes", "package name for generated files")
	flag.Parse()

	docs, err := loadDocuments(*docsDir)
	if err != nil {
		fatal(err)
	}
	if len(docs) == 0 {
		fatal(fmt.Errorf("no Markdown files found in %s", *docsDir))
	}

	if err := os.MkdirAll(*outDir, 0o755); err != nil {
		fatal(err)
	}

	manifest := &bytes.Buffer{}
	fmt.Fprintf(manifest, "// Code generated by tools/md2go; DO NOT EDIT.\n\n")
	fmt.Fprintf(manifest, "package %s\n\n", *pkg)
	fmt.Fprintf(manifest, "var generatedDocs = []markdownDoc{\n")
	for _, doc := range docs {
		fmt.Fprintf(manifest, "\t{\n")
		fmt.Fprintf(manifest, "\t\tSlug: %s,\n", strconv.Quote(doc.Slug))
		fmt.Fprintf(manifest, "\t\tTitle: %s,\n", strconv.Quote(doc.Title))
		fmt.Fprintf(manifest, "\t\tSummary: %s,\n", strconv.Quote(doc.Summary))
		fmt.Fprintf(manifest, "\t\tMarkdown: %s,\n", doc.Const)
		fmt.Fprintf(manifest, "\t},\n")
	}
	fmt.Fprintf(manifest, "}\n")

	if err := writeFormatted(filepath.Join(*outDir, "docs_manifest.go"), manifest.Bytes()); err != nil {
		fatal(err)
	}

	for _, doc := range docs {
		source, err := os.ReadFile(doc.Filename)
		if err != nil {
			fatal(err)
		}

		file := &bytes.Buffer{}
		fmt.Fprintf(file, "// Code generated by tools/md2go from docs/%s; DO NOT EDIT.\n\n", filepath.Base(doc.Filename))
		fmt.Fprintf(file, "package %s\n\n", *pkg)
		fmt.Fprintf(file, "const %s = \"\" +\n", doc.Const)
		for _, line := range linesWithEnding(string(source)) {
			fmt.Fprintf(file, "\t%s +\n", strconv.Quote(line))
		}
		file.WriteString("\t\"\"\n")

		name := fmt.Sprintf("docs_%s.go", strings.ReplaceAll(doc.Slug, "-", "_"))
		if err := writeFormatted(filepath.Join(*outDir, name), file.Bytes()); err != nil {
			fatal(err)
		}
		fmt.Printf("generated %s from %s\n", filepath.Join(*outDir, name), doc.Filename)
	}
	fmt.Printf("generated %s\n", filepath.Join(*outDir, "docs_manifest.go"))
}

func loadDocuments(dir string) ([]document, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}

	var docs []document
	for _, entry := range entries {
		if entry.IsDir() || !strings.EqualFold(filepath.Ext(entry.Name()), ".md") {
			continue
		}

		filename := filepath.Join(dir, entry.Name())
		source, err := os.ReadFile(filename)
		if err != nil {
			return nil, err
		}

		slug := strings.TrimSuffix(entry.Name(), filepath.Ext(entry.Name()))
		slug = strings.ToLower(strings.ReplaceAll(slug, "_", "-"))
		title, summary := metadata(string(source))
		if title == "" {
			title = titleCase(slug)
		}

		docs = append(docs, document{
			Slug:     slug,
			Title:    title,
			Summary:  summary,
			Filename: filename,
			Const:    "docs" + camel(slug) + "Markdown",
		})
	}

	sort.Slice(docs, func(i, j int) bool {
		return docs[i].Slug < docs[j].Slug
	})

	return docs, nil
}

func metadata(source string) (title, summary string) {
	lines := strings.Split(source, "\n")
	paragraph := make([]string, 0, 4)
	inFence := false

	for _, line := range lines {
		trimmed := strings.TrimSpace(line)

		if strings.HasPrefix(trimmed, "```") {
			inFence = !inFence
			continue
		}
		if inFence {
			continue
		}

		if title == "" && strings.HasPrefix(trimmed, "# ") {
			title = strings.TrimSpace(strings.TrimPrefix(trimmed, "# "))
			continue
		}

		if title == "" {
			continue
		}

		if trimmed == "" {
			if len(paragraph) > 0 {
				break
			}
			continue
		}

		if strings.HasPrefix(trimmed, "#") ||
			strings.HasPrefix(trimmed, "|") ||
			strings.HasPrefix(trimmed, ">") ||
			strings.HasPrefix(trimmed, "- ") ||
			strings.HasPrefix(trimmed, "* ") ||
			strings.HasPrefix(trimmed, "---") {
			if len(paragraph) > 0 {
				break
			}
			continue
		}

		paragraph = append(paragraph, trimmed)
	}

	summary = plainText(strings.Join(paragraph, " "))
	if len(summary) > 180 {
		summary = strings.TrimSpace(summary[:177]) + "..."
	}

	return title, summary
}

// plainText removes the most common inline Markdown markers so summaries can be
// displayed as plain text (or safely HTML-escaped) in card and page headers.
func plainText(value string) string {
	value = markdownLink.ReplaceAllString(value, "$1")
	value = markdownCode.ReplaceAllString(value, "")
	value = markdownBold.ReplaceAllString(value, "")
	value = markdownEm.ReplaceAllString(value, "")
	return strings.TrimSpace(value)
}

func linesWithEnding(source string) []string {
	if source == "" {
		return nil
	}

	lines := strings.SplitAfter(source, "\n")
	if len(lines) > 0 && lines[len(lines)-1] == "" {
		lines = lines[:len(lines)-1]
	}
	return lines
}

func camel(value string) string {
	var out strings.Builder
	upper := true
	for _, r := range value {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			upper = true
			continue
		}
		if upper {
			out.WriteRune(unicode.ToUpper(r))
			upper = false
			continue
		}
		out.WriteRune(r)
	}
	return out.String()
}

func titleCase(slug string) string {
	words := strings.FieldsFunc(slug, func(r rune) bool {
		return r == '-' || r == '_'
	})
	for i, word := range words {
		if word == "" {
			continue
		}
		runes := []rune(word)
		runes[0] = unicode.ToUpper(runes[0])
		words[i] = string(runes)
	}
	return strings.Join(words, " ")
}

func writeFormatted(path string, source []byte) error {
	formatted, err := format.Source(source)
	if err != nil {
		return fmt.Errorf("format %s: %w\n%s", path, err, source)
	}
	return os.WriteFile(path, formatted, 0o644)
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "md2go:", err)
	os.Exit(1)
}
